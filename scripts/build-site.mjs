import {metadata as archive} from './build-studio.mjs';
import {mkdir,writeFile,access,readFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {curatedConcepts} from '../src/curated/catalog.mjs';
import {categoryNames} from '../src/studio/catalog.mjs';
import {renderCuratedPage} from '../src/curated/page.mjs';
import {renderCuratedGallery} from '../src/curated/gallery.mjs';
import {renderComparison} from '../src/studio/gallery.mjs';
import {renderScreenshots} from '../src/curated/screenshots.mjs';
import {freshConcepts} from '../src/fresh/catalog.mjs';
import {renderFreshPage} from '../src/fresh/page.mjs';
import {renderFreshGallery} from '../src/fresh/gallery.mjs';
import {buildTrio} from './build-trio.mjs';
import {buildMood} from './build-mood.mjs';
import {buildSelection} from './build-selection.mjs';
import {selectEntries} from '../src/selection/catalog.mjs';
import {buildRestart} from './build-restart.mjs';
import {buildAtelier} from './build-atelier.mjs';
import {buildNext} from './build-next.mjs';

const dist=fileURLToPath(new URL('../dist/',import.meta.url));
const exists=async filename=>{
  try{await access(filename);return true;}catch(error){if(error.code==='ENOENT')return false;throw error;}
};
async function mediaVersionFor(directory,folders){
  const hash=createHash('sha256');
  for(const name of folders){
    const folder=path.join(dist,directory,name);
    let files;
    try{files=await readdir(folder,{withFileTypes:true});}catch(error){if(error.code==='ENOENT')continue;throw error;}
    for(const file of files.filter(item=>item.isFile()).sort((a,b)=>a.name.localeCompare(b.name))){
      hash.update(`${name}/${file.name}`).update(await readFile(path.join(folder,file.name)));
    }
  }
  return hash.digest('hex').slice(0,10);
}
const assetVersions={};
for(const name of ['final','heroes','gallery','polish','motion'])assetVersions[name]=createHash('sha256').update(await readFile(path.join(dist,'final',`${name}.${name==='motion'?'js':'css'}`))).digest('hex').slice(0,10);
await writeFile(path.join(dist,'final','final.js'),`// Generated bootstrap; shared form/menu behaviour plus optional presentation effects.\nimport '../studio/site.js';\nimport {initPresentationEffects} from './motion.js?v=${assetVersions.motion}';\ninitPresentationEffects();\n`);
const mediaVersion=await mediaVersionFor('final',['previews','screens','sets']);
await mkdir(path.join(dist,'final'),{recursive:true});
const finals=[];
for(const concept of curatedConcepts){
  await writeFile(path.join(dist,'final',`${concept.id}.html`),renderCuratedPage(concept,curatedConcepts,assetVersions));
  const thumbnail=`final/previews/${concept.id}.webp`;
  const hasThumbnail=await exists(path.join(dist,thumbnail));
  finals.push({...concept,href:`final/${concept.id}.html`,edition:'curated',collection:'curated',thumbnail:hasThumbnail?`${thumbnail}?v=${mediaVersion}`:null,mediaVersion,categoryName:categoryNames[concept.category]});
}
const previous=archive.map(item=>({...item,edition:'archive'}));
await mkdir(path.join(dist,'fresh'),{recursive:true});
const freshHash=createHash('sha256');
for(const name of ['fresh.css','layouts.css','fresh.js'])freshHash.update(name).update(await readFile(path.join(dist,'fresh',name)));
const freshAssetVersion=freshHash.digest('hex').slice(0,10);
const freshMediaVersion=await mediaVersionFor('fresh',['previews','screens']);
const fresh=[];
for(const concept of freshConcepts){
  await writeFile(path.join(dist,'fresh',`${concept.id}.html`),renderFreshPage(concept,freshConcepts,freshAssetVersion));
  const thumbnail=`fresh/previews/${concept.id}.webp`;
  const screenshots={};
  for(const size of ['desktop','mobile']){
    const screenshot=`fresh/screens/${concept.id}-${size}.webp`;
    if(await exists(path.join(dist,screenshot)))screenshots[size]=`${screenshot}?v=${freshMediaVersion}`;
  }
  fresh.push({...concept,href:`fresh/${concept.id}.html`,edition:'fresh',collection:'fresh',thumbnail:await exists(path.join(dist,thumbnail))?`${thumbnail}?v=${freshMediaVersion}`:null,screenshots,mediaVersion:freshMediaVersion,categoryName:categoryNames[concept.category]});
}
const trio=await buildTrio(dist);
const mood=await buildMood(dist);
const all=[...mood,...trio,...fresh,...finals,...previous];
await writeFile(path.join(dist,'studio','catalog.js'),`// Generated by scripts/build-site.mjs.\nexport default ${JSON.stringify(all,null,2)};\n`);
const catalogVersion=createHash('sha256').update(JSON.stringify(all)).digest('hex').slice(0,10);
for(const filename of ['collection.js','compare.js']){
  const contents=await readFile(path.join(dist,filename),'utf8');
  await writeFile(path.join(dist,filename),contents.replace(/from '\.\/studio\/catalog\.js(?:\?v=[a-f0-9]+)?'/,`from './studio/catalog.js?v=${catalogVersion}'`));
}
const collectionHash=createHash('sha256');
for(const filename of ['collection.js','preferences.js','studio/catalog.js'])collectionHash.update(filename).update(await readFile(path.join(dist,filename)));
await writeFile(path.join(dist,'fresh.html'),renderFreshGallery(fresh,{assetVersion:assetVersions.gallery,collectionVersion:collectionHash.digest('hex').slice(0,10)}));
const collectionVersion=createHash('sha256').update(await readFile(path.join(dist,'collection.js'))).digest('hex').slice(0,10);
const compareVersion=createHash('sha256').update(await readFile(path.join(dist,'compare.js'))).digest('hex').slice(0,10);
await writeFile(path.join(dist,'collection.html'),renderCuratedGallery(finals,previous,{assetVersion:assetVersions.gallery}).replace('src="collection.js"',`src="collection.js?v=${collectionVersion}"`));
await writeFile(path.join(dist,'archive.html'),renderCuratedGallery(previous,previous,{archive:true,assetVersion:assetVersions.gallery}).replace('src="collection.js"',`src="collection.js?v=${collectionVersion}"`));
const shortlist=selectEntries(all).map(entry=>({...entry,shortlisted:true}));
const shortlistIds=new Set(shortlist.map(entry=>entry.id));
await writeFile(path.join(dist,'compare.html'),renderComparison([...shortlist,...all.filter(entry=>!shortlistIds.has(entry.id))]).replace('src="compare.js"',`src="compare.js?v=${compareVersion}"`));
await writeFile(path.join(dist,'screenshots.html'),renderScreenshots(finals,assetVersions.gallery,mediaVersion));
await buildSelection(dist,all);
await buildRestart(dist);
await buildAtelier(dist);
await buildNext(dist);
console.log(`Built ${mood.length} reference-led designs, ${trio.length} text-brief designs, ${fresh.length} fresh concepts and ${finals.length} improved finalists; all ${previous.length} earlier variants remain available in the archive (${all.length} total).`);
