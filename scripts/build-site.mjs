import {metadata as archive} from './build-studio.mjs';
import {mkdir,writeFile,access,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {curatedConcepts} from '../src/curated/catalog.mjs';
import {categoryNames} from '../src/studio/catalog.mjs';
import {renderCuratedPage} from '../src/curated/page.mjs';
import {renderCuratedGallery} from '../src/curated/gallery.mjs';
import {renderComparison} from '../src/studio/gallery.mjs';
import {renderScreenshots} from '../src/curated/screenshots.mjs';

const dist=fileURLToPath(new URL('../dist/',import.meta.url));
const assetVersions={};
for(const name of ['final','heroes','gallery'])assetVersions[name]=createHash('sha256').update(await readFile(path.join(dist,'final',`${name}.css`))).digest('hex').slice(0,10);
await mkdir(path.join(dist,'final'),{recursive:true});
const finals=[];
for(const concept of curatedConcepts){
  await writeFile(path.join(dist,'final',`${concept.id}.html`),renderCuratedPage(concept,curatedConcepts,assetVersions));
  const thumbnail=`final/previews/${concept.id}.webp`;
  let hasThumbnail=false;
  try{await access(path.join(dist,thumbnail));hasThumbnail=true;}catch{/* Captured from the real page after visual review. */}
  finals.push({...concept,href:`final/${concept.id}.html`,edition:'curated',collection:'curated',thumbnail:hasThumbnail?thumbnail:null,categoryName:categoryNames[concept.category]});
}
const previous=archive.map(item=>({...item,edition:'archive'}));
const all=[...finals,...previous];
await writeFile(path.join(dist,'studio','catalog.js'),`// Generated by scripts/build-site.mjs.\nexport default ${JSON.stringify(all,null,2)};\n`);
await writeFile(path.join(dist,'collection.html'),renderCuratedGallery(finals,previous,{assetVersion:assetVersions.gallery}));
await writeFile(path.join(dist,'archive.html'),renderCuratedGallery(previous,previous,{archive:true,assetVersion:assetVersions.gallery}));
await writeFile(path.join(dist,'compare.html'),renderComparison(all));
await writeFile(path.join(dist,'screenshots.html'),renderScreenshots(finals,assetVersions.gallery));
console.log(`Built ${finals.length} improved finalists; all ${previous.length} earlier variants remain available in the archive.`);
