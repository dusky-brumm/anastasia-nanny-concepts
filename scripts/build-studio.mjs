import { mkdir, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { concepts, legacyConcepts, categoryNames } from '../src/studio/catalog.mjs';
import { heroes } from '../src/studio/heroes.mjs';
import { renderPage } from '../src/studio/page.mjs';
import { renderGallery, renderComparison } from '../src/studio/gallery.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root,'dist');
const output = path.join(dist,'studio');
await mkdir(output,{recursive:true});
await mkdir(path.join(root,'project-notes'),{recursive:true});
const available = concepts.filter(concept=>typeof heroes[concept.hero]==='function');
for (const concept of available) await writeFile(path.join(output,`${concept.id}.html`),renderPage(concept,available));
const metadata = [];
for (const concept of [...available.map(item=>({...item,href:`studio/${item.id}.html`,collection:'new'})),...legacyConcepts.map(item=>({...item,collection:'earlier'}))]) {
  const thumbnail = `studio/previews/${concept.id}.webp`;
  let hasThumbnail = false;
  try { await access(path.join(dist,thumbnail)); hasThumbnail = true; } catch { /* Added after screenshot QA. */ }
  metadata.push({ ...concept, thumbnail:hasThumbnail?thumbnail:null, categoryName:categoryNames[concept.category] });
}
await writeFile(path.join(output,'catalog.js'),`// Generated by scripts/build-studio.mjs.\nexport default ${JSON.stringify(metadata,null,2)};\n`);
await writeFile(path.join(dist,'collection.html'),renderGallery(metadata,available.length));
await writeFile(path.join(dist,'compare.html'),renderComparison(metadata));
await writeFile(path.join(root,'project-notes','build-state.json'),JSON.stringify({ built:available.map(item=>item.id),planned:concepts.filter(item=>!available.includes(item)).map(item=>item.id),expectedNew:20 },null,2)+'\n');
console.log(`Built ${available.length}/20 new directions and preserved ${legacyConcepts.length} existing directions.`);
